export const CLARIFY_PREFIX = 'CLARIFY:';

const TOOL_POLICY = `Доступные инструменты: get_schema, list_entities, search_entities, read_entity, write_fact, create_entity, add_alias, propose_schema_change.

Правила:
- Используй ТОЛЬКО перечисленные выше MCP-инструменты. Никогда не запускай команды, не читай и не пиши файлы напрямую своими встроенными инструментами — вся работа с vault идёт исключительно через эти MCP-инструменты.
- Перед записью факта сначала найди существующую сущность через search_entities/list_entities — не создавай дубликат, если сущность уже есть под другим написанием имени.
- Если нужно записать НЕСКОЛЬКО фактов об одной и той же сущности (например, из одного сообщения) — ищи её ОДИН раз, не повторяй поиск отдельно для каждого факта или атрибута. Один найденный человек = один поиск, а не поиск по имени, потом по нику, потом по городу и т.д.
- Записывай факты только через write_fact или create_entity — никогда не изменяй файлы напрямую.
- Если у существующей сущности появилось другое имя/прозвище — добавь его через add_alias, а не через create_entity.
- Не читай весь vault целиком — используй search_entities/read_entity только для сущностей, релевантных сообщению или вопросу.
- Факты о событии (кто что сделал НА событии) пиши в файл события типа "event" со ссылками [[Имя]] на участников — не дублируй их в файл человека. Но если событие упомянуто мимоходом, без даты и деталей (например, "был на моей свадьбе", "встречались на дне рождения") — не пытайся искать или заводить для него отдельную сущность события, просто запиши это обычным фактом на сущность человека.
- Если стоит вынести повторяющийся факт в YAML-схему или завести новый тип сущности — вызови propose_schema_change и упомяни это в финальном ответе. Ты только предлагаешь изменение — применяет его сам пользователь командой /confirm_schema.
- Если не хватает информации, чтобы понять, о ком или о чём речь (например, несколько сущностей с похожим именем) — не вызывай больше инструментов и верни ответ СТРОГО в формате "${CLARIFY_PREFIX} <твой уточняющий вопрос>", без ничего лишнего.`;

export function buildMessagePrompt(message: string): string {
  return `${TOOL_POLICY}

Сообщение пользователя: """${message}"""

Сначала определи сам, это новый факт для записи или вопрос о ранее записанных фактах:
- Если это факт — запиши его через write_fact/create_entity и в конце кратко напиши по-русски, что записано.
- Если это вопрос — ответь кратко по-русски, основываясь только на найденных данных. Если данных недостаточно, так и скажи.`;
}

export function buildClarificationPrompt(originalMessage: string, question: string, answer: string): string {
  return `${TOOL_POLICY}

Ранее на сообщение пользователя:
"""${originalMessage}"""
был задан уточняющий вопрос: "${question}"
Пользователь ответил: "${answer}"

Продолжи обработку исходного сообщения с учётом уточнения так же, как описано выше (запись факта или ответ на вопрос).`;
}
